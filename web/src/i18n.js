export let currentLang = "nb";

export function setLang(lang) { currentLang = I18N[lang] ? lang : "nb"; return currentLang; }

export function detectInitialLanguage() {
    var saved = localStorage.getItem("ui-lang");
    if (saved === "no") {
      saved = "nb";
    }
    if (saved && I18N[saved]) {
      return saved;
    }
    var browserLang = (navigator.language || "nb").toLowerCase();
    if (browserLang.indexOf("nn") === 0) {
      return "nn";
    }
    if (browserLang.indexOf("en") === 0) {
      return "en";
    }
    if (browserLang.indexOf("sv") === 0) {
      return "sv";
    }
    return "nb";
  }


