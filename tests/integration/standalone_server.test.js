const { spawn } = require('child_process');
const http = require('http');
const fs = require('fs');
const path = require('path');
const assert = require('node:assert/strict');

const rootDir = path.resolve(__dirname, '..', '..');
const standaloneDir = path.join(rootDir, 'standalonePS');
const serverScript = path.join(standaloneDir, 'server.ps1');
const dataDir = path.join(standaloneDir, 'data');
const sourceFile = path.join(dataDir, 'source.json');

const testPort = 8899;

function request(options, postData) {
  return new Promise((resolve, reject) => {
    const req = http.request(options, res => {
      let data = '';
      res.on('data', chunk => data += chunk);
      res.on('end', () => resolve({ status: res.statusCode, headers: res.headers, body: data }));
    });
    req.on('error', reject);
    if (postData) req.write(postData);
    req.end();
  });
}

function sleep(ms) {
  return new Promise(r => setTimeout(r, ms));
}

(async () => {
  console.log('=== Integration: Standalone PowerShell HTTP Server & /api/save ===');

  if (!fs.existsSync(serverScript)) {
    console.error(`❌ server.ps1 not found at ${serverScript}`);
    process.exit(1);
  }

  // Preserve original source.json before testing save
  let originalSourceContent = null;
  if (fs.existsSync(sourceFile)) {
    originalSourceContent = fs.readFileSync(sourceFile, 'utf8');
  }

  // Record existing backups so we know which ones to clean up
  const existingBackups = new Set(
    fs.existsSync(dataDir) ? fs.readdirSync(dataDir).filter(f => f.startsWith('source.backup-')) : []
  );

  console.log(`Starting standalonePS/server.ps1 on port ${testPort}...`);
  const ps = spawn('powershell.exe', [
    '-NoProfile',
    '-ExecutionPolicy', 'Bypass',
    '-File', serverScript,
    '-Port', String(testPort)
  ], {
    cwd: standaloneDir,
    stdio: 'pipe'
  });

  ps.stdout.on('data', d => {
    // console.log('[server stdout]', d.toString());
  });
  ps.stderr.on('data', d => {
    console.error('[server stderr]', d.toString());
  });

  let serverStarted = false;
  // Wait up to 8 seconds for server to bind port
  for (let i = 0; i < 16; i++) {
    await sleep(500);
    try {
      const res = await request({
        hostname: 'localhost',
        port: testPort,
        path: '/web/index.html',
        method: 'GET',
        timeout: 1000
      });
      if (res.status === 200) {
        serverStarted = true;
        break;
      }
    } catch (_) {}
  }

  if (!serverStarted) {
    ps.kill();
    throw new Error('PowerShell server failed to start or respond on port ' + testPort);
  }

  console.log(' - PowerShell server started and responding.');

  try {
    // 1. Test Static File Serving
    console.log('1. Testing static file serving (/web/index.html)...');
    const resHtml = await request({
      hostname: 'localhost',
      port: testPort,
      path: '/web/index.html',
      method: 'GET'
    });
    assert.equal(resHtml.status, 200);
    assert.equal(resHtml.headers['content-type'].includes('text/html'), true);
    assert.equal(resHtml.body.includes('Menighetsbladet'), true);
    console.log('   ✓ Static HTML served correctly.');

    // 2. Test Canonical Data Serving
    console.log('2. Testing data serving (/data/source.json)...');
    const resData = await request({
      hostname: 'localhost',
      port: testPort,
      path: '/data/source.json',
      method: 'GET'
    });
    assert.equal(resData.status, 200);
    assert.equal(resData.headers['content-type'].includes('application/json'), true);
    console.log('   ✓ Data JSON served correctly.');

    // 3. Test /api/save & Backup Creation
    console.log('3. Testing POST /api/save endpoint and backup creation...');
    const testPayload = JSON.stringify({
      server_integration_test: true,
      timestamp: Date.now()
    });

    const resSave = await request({
      hostname: 'localhost',
      port: testPort,
      path: '/api/save',
      method: 'POST',
      headers: {
        'Content-Type': 'application/json; charset=utf-8',
        'Content-Length': Buffer.byteLength(testPayload)
      }
    }, testPayload);

    assert.equal(resSave.status, 200);
    const saveJson = JSON.parse(resSave.body);
    assert.equal(saveJson.ok, true);
    console.log('   ✓ /api/save returned { ok: true }');

    // Verify source.json was updated
    const savedOnDisk = fs.readFileSync(sourceFile, 'utf8');
    assert.equal(savedOnDisk, testPayload);
    console.log('   ✓ Data written to disk correctly.');

    // Verify timestamped backup was generated
    const newBackups = fs.readdirSync(dataDir).filter(f => f.startsWith('source.backup-') && !existingBackups.has(f));
    assert.equal(newBackups.length > 0, true, 'At least one backup file should be generated by /api/save');
    console.log(`   ✓ Backup file generated: ${newBackups.join(', ')}`);

    // Clean up created test backups
    newBackups.forEach(b => {
      try { fs.unlinkSync(path.join(dataDir, b)); } catch (_) {}
    });

    console.log('🎉 STANDALONE SERVER & /api/save INTEGRATION VERIFIED!\n');
  } finally {
    // Restore original source.json
    if (originalSourceContent !== null) {
      fs.writeFileSync(sourceFile, originalSourceContent, 'utf8');
      console.log(' - Restored original standalone source.json.');
    }
    // Kill PowerShell process
    try {
      ps.kill('SIGTERM');
      spawn('taskkill', ['/pid', ps.pid, '/f', '/t']);
    } catch (_) {}
  }
})().catch(err => {
  console.error('❌ Test failed:', err);
  process.exit(1);
});

